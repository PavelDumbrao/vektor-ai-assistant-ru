ALTER TABLE passive_secretary.messages
    ADD COLUMN IF NOT EXISTS last_update_id BIGINT NOT NULL DEFAULT 0;
ALTER TABLE passive_secretary.messages
    ADD COLUMN IF NOT EXISTS ingest_origin TEXT NOT NULL DEFAULT 'business_update';

-- Older deployments created an inline CHECK without a stable name. Replace
-- only the known column-level constraint so group_update can be introduced
-- without weakening the origin allowlist.
DO $$
DECLARE constraint_name TEXT;
BEGIN
    SELECT con.conname INTO constraint_name
    FROM pg_constraint AS con
    JOIN pg_class AS rel ON rel.oid=con.conrelid
    JOIN pg_namespace AS ns ON ns.oid=rel.relnamespace
    WHERE ns.nspname='passive_secretary'
      AND rel.relname='messages'
      AND con.contype='c'
      AND pg_get_constraintdef(con.oid) LIKE '%ingest_origin%'
    LIMIT 1;
    IF constraint_name IS NOT NULL THEN
        EXECUTE format(
            'ALTER TABLE passive_secretary.messages DROP CONSTRAINT %I',
            constraint_name
        );
    END IF;
END $$;
ALTER TABLE passive_secretary.messages
    ADD CONSTRAINT messages_ingest_origin_check
    CHECK (ingest_origin IN ('business_update', 'group_update', 'history_backfill'));

-- Nullable metadata columns make this upgrade safe for existing archives.
-- Raw Telegram relation identifiers remain storage-only; retrieval exposes
-- only the keyed opaque references generated by the normalizer.
ALTER TABLE passive_secretary.messages
