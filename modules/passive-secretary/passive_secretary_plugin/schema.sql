CREATE TABLE IF NOT EXISTS passive_secretary.media_enrichments (
    tenant_id TEXT NOT NULL,
    tenant_owner_id BIGINT NOT NULL,
    source_id TEXT NOT NULL,
    test_run_id TEXT NOT NULL DEFAULT '',
    chat_id BIGINT NOT NULL,
    message_id BIGINT NOT NULL,
    media_index INTEGER NOT NULL CHECK (media_index BETWEEN 0 AND 7),
    business_connection_id TEXT NOT NULL,
    file_unique_id TEXT NOT NULL,
    job_id TEXT NOT NULL,
    media_kind TEXT NOT NULL CHECK (media_kind IN ('voice', 'video_note', 'document')),
    status TEXT NOT NULL CHECK (
        status IN (
            'transcribed', 'unsupported', 'too_large',
            'download_failed_permanent', 'asr_failed_permanent'
        )
    ),
    transcript TEXT,
    language TEXT,
    content_sha256 TEXT,
    actual_bytes BIGINT,
    duration_ms BIGINT,
    processor_service TEXT NOT NULL,
    processor_version TEXT NOT NULL,
    processor_engine TEXT NOT NULL,
    processor_model TEXT NOT NULL,
    processor_quantization TEXT NOT NULL,
    source_update_id BIGINT NOT NULL,
    received_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (
        tenant_id, tenant_owner_id, source_id, test_run_id,
        chat_id, message_id, media_index, processor_version
    ),
    UNIQUE (tenant_id, tenant_owner_id, source_id, test_run_id, job_id),
    FOREIGN KEY (tenant_id, tenant_owner_id, source_id, test_run_id, chat_id, message_id)
        REFERENCES passive_secretary.messages
        (tenant_id, tenant_owner_id, source_id, test_run_id, chat_id, message_id)
        ON DELETE CASCADE,
    CHECK (
        (status='transcribed' AND transcript IS NOT NULL)
        OR (status<>'transcribed' AND transcript IS NULL AND language IS NULL)
    ),
    CHECK (actual_bytes IS NULL OR actual_bytes BETWEEN 0 AND 20971520),
    CHECK (duration_ms IS NULL OR duration_ms BETWEEN 0 AND 1800000)
);

CREATE INDEX IF NOT EXISTS media_enrichments_message_idx
    ON passive_secretary.media_enrichments
    (tenant_id, tenant_owner_id, source_id, test_run_id, chat_id, message_id, media_index);

CREATE TABLE IF NOT EXISTS passive_secretary.outbound_intents (
    tenant_id TEXT NOT NULL,
    tenant_owner_id BIGINT NOT NULL,
    source_id TEXT NOT NULL,
    test_run_id TEXT NOT NULL DEFAULT '',
    intent_id TEXT NOT NULL,
    session_ref TEXT NOT NULL,
    source_ref TEXT NOT NULL,
    message_hmac TEXT NOT NULL,
    chat_id BIGINT NOT NULL,
    business_connection_id TEXT NOT NULL,
    anchor_message_id BIGINT NOT NULL,
    reply_message_id BIGINT,
    status TEXT NOT NULL CHECK (
        status IN (
            'prepared', 'sending', 'sent', 'denied', 'failed_known', 'ambiguous'
        )
    ),
    expires_at TIMESTAMPTZ NOT NULL,
    telegram_message_id BIGINT,
    failure_code TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (
        tenant_id, tenant_owner_id, source_id, test_run_id, intent_id
    ),
    CHECK (telegram_message_id IS NULL OR telegram_message_id > 0),
    CHECK (anchor_message_id > 0),
    CHECK (reply_message_id IS NULL OR reply_message_id > 0)
);

CREATE INDEX IF NOT EXISTS outbound_intents_scope_status_idx
    ON passive_secretary.outbound_intents
    (tenant_id, tenant_owner_id, source_id, test_run_id, status, updated_at DESC);
CREATE INDEX IF NOT EXISTS outbound_intents_payload_anchor_idx
    ON passive_secretary.outbound_intents
    (tenant_id, tenant_owner_id, source_id, test_run_id,
     source_ref, message_hmac, anchor_message_id, created_at DESC);

